import { breakpointTokens } from "./breakpoints.js";
import { flattenColorTokens, type ColorTheme } from "./color.js";
import { motionTokens } from "./motion.js";
import { radiusTokens } from "./radius.js";
import { shadowTokens } from "./shadow.js";
import { spaceTokens } from "./space.js";
import { BANGLA_LINE_HEIGHT, fontSizeTokens, fontWeightTokens } from "./typography.js";
import { zIndexTokens } from "./z-index.js";

const HEADER = "/* Generated by scripts/build-tokens.mjs from src/tokens. Do not edit by hand. */";
const INDENT = "  ";

type Declaration = readonly [name: string, value: string];

function toKebab(name: string): string {
  return name
    .replaceAll(".", "-")
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .toLowerCase();
}

/** Lowercase hex is what Prettier writes, so the committed file stays format-clean. */
function colorDeclarations(theme: ColorTheme): Declaration[] {
  return flattenColorTokens().map(({ name, value }) => [
    `--color-${toKebab(name)}`,
    value[theme].toLowerCase(),
  ]);
}

function scaleDeclarations(prefix: string, scale: Record<string, string>): Declaration[] {
  return Object.entries(scale).map(([key, value]) => [`--token-${prefix}-${toKebab(key)}`, value]);
}

function fontDeclarations(): Declaration[] {
  const sizes = Object.entries(fontSizeTokens).flatMap(([key, { size, lineHeight }]) => [
    [`--token-font-size-${toKebab(key)}`, size] as const,
    [`--token-line-height-${toKebab(key)}`, lineHeight] as const,
  ]);
  return [
    ...sizes,
    ...scaleDeclarations("font-weight", fontWeightTokens),
    ["--token-line-height-bangla", BANGLA_LINE_HEIGHT],
  ];
}

function sharedDeclarations(): Declaration[] {
  return [
    ...fontDeclarations(),
    ...scaleDeclarations("space", spaceTokens),
    ...scaleDeclarations("radius", radiusTokens),
    ...scaleDeclarations("shadow", shadowTokens),
    ...scaleDeclarations("motion", motionTokens),
    ...scaleDeclarations("z", zIndexTokens),
    ...scaleDeclarations("breakpoint", breakpointTokens),
  ];
}

function renderBlock(selector: string, declarations: readonly Declaration[]): string {
  const lines = declarations.map(([name, value]) => `${INDENT}${name}: ${value};`);
  return [`${selector} {`, ...lines, "}"].join("\n");
}

/** Output must already be Prettier-formatted, so `format:check` passes on the committed file. */
export function renderTokensCss(): string {
  const lightBlock = renderBlock(":root", [...colorDeclarations("light"), ...sharedDeclarations()]);
  const darkBlock = renderBlock('[data-theme="dark"]', colorDeclarations("dark"));
  return `${HEADER}\n${lightBlock}\n\n${darkBlock}\n`;
}
