export type EditorLabelKey = (typeof EDITOR_LABEL_KEYS)[number];
export type EditorLabels = Readonly<Record<EditorLabelKey, string>>;

export function editorLabelsOf(t: Translator["t"]): EditorLabels {
  const entries = EDITOR_LABEL_KEYS.map((key) => [key, t(`catalog.${key}`)]);
  // Safe: entries has exactly one text for each key of EDITOR_LABEL_KEYS.
  return Object.fromEntries(entries) as EditorLabels;
}

/** Fills the {name} placeholders of a label. */
export function fillLabel(
  label: string,
  values: Readonly<Record<string, string | number>>,
): string {
  return label.replace(/\{(\w+)\}/gu, (placeholder, name: string) =>
    String(values[name] ?? placeholder),
  );
}
